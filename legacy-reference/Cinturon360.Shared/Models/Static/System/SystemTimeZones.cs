    // INDEXES (O(1) lookups)
    // ------------------------------------------------------------------------

    private static readonly IReadOnlyDictionary<int, SystemTimeZoneInfo> _byId =
        _all.ToDictionary(x => x.Id);

    private static readonly IReadOnlyDictionary<string, SystemTimeZoneInfo> _byIanaId =
        _all.ToDictionary(x => x.IanaId, StringComparer.OrdinalIgnoreCase);

    // ------------------------------------------------------------------------
    // LOOKUPS
    // ------------------------------------------------------------------------

    public static SystemTimeZoneInfo Get(SystemTimeZone type)
        => Get((int)type);

    public static SystemTimeZoneInfo Get(int id)
        => _byId[id];

    public static SystemTimeZoneInfo? TryGet(int id)
        => _byId.TryGetValue(id, out var value) ? value : null;

    public static SystemTimeZoneInfo GetByIanaId(string ianaId)
        => _byIanaId[ianaId];

    public static SystemTimeZoneInfo? TryGetByIanaId(string ianaId)
        => _byIanaId.TryGetValue(ianaId, out var value) ? value : null;

    public static SystemTimeZone ToEnum(int id)
        => (SystemTimeZone)id;

    public static int ToId(SystemTimeZone type)
        => (int)type;

