    // ------------------------------------------------------------------------
    // RECORD MODEL (source of truth)
    // ------------------------------------------------------------------------

    public sealed record SystemTimeZoneInfo(
        int Id,
        string Code,
        string CodeLower,
        string IanaId,
        string DisplayName,
        string StandardName,
        string DaylightName,
        TimeSpan BaseUtcOffset,
        bool SupportsDaylightSavingTime
    )
    {
        public SystemTimeZone Enum =>
            (SystemTimeZone)Id;
    }

    // ------------------------------------------------------------------------
    // SYSTEM SOURCE
    // ------------------------------------------------------------------------

    private static readonly IReadOnlyDictionary<string, TimeZoneInfo> _system =
        TimeZoneInfo
            .GetSystemTimeZones()
            .ToDictionary(x => x.Id, StringComparer.OrdinalIgnoreCase);

    private static SystemTimeZoneInfo Create(
        int id,
        string ianaId)
    {
        var tz = _system.TryGetValue(ianaId, out var found)
            ? found
            : TimeZoneInfo.Utc;

        return new SystemTimeZoneInfo(
            id,
            ianaId.Replace("/", "_").ToUpperInvariant(),
            ianaId.Replace("/", "_").ToLowerInvariant(),
            tz.Id,
            tz.DisplayName,
            tz.StandardName,
            tz.DaylightName,
            tz.BaseUtcOffset,
            tz.SupportsDaylightSavingTime);
    }

